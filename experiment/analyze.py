"""Paired, cluster-bootstrap analysis of saved scores; never invokes a model.

Input is scores.jsonl from prototype.py evaluate, from exactly ONE dataset,
model, prompt configuration and generation replicate. No synthetic results
are generated by this command. Intervals reflect dataset-cluster sampling,
not variation across model seeds or uncertainty in human annotations.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import random

METRICS = ('answer_em', 'joint_exact_evidence')


def load_groups(rows):
    groups = defaultdict(dict)
    seen_ids = set()
    if not rows:
        raise ValueError('Empty score file')
    for row in rows:
        for field in ('id', 'sample_id', 'cluster_id', 'method'):
            if not isinstance(row.get(field), str) or not row[field]:
                raise ValueError(f'Missing or invalid {field}')
        if type(row.get('budget')) is not int or row['budget'] < 0:
            raise ValueError('Budget must be a nonnegative integer')
        for field in (*METRICS, 'valid', 'missing'):
            if type(row.get(field)) is not int or row[field] not in (0, 1):
                raise ValueError(f'{field} must be 0 or 1')
        if row['joint_exact_evidence'] > row['answer_em'] or row['answer_em'] > row['valid']:
            raise ValueError('Inconsistent validity/answer/joint scores')
        if row['missing'] and (row['valid'] or row['answer_em'] or row['joint_exact_evidence']):
            raise ValueError('Missing predictions must remain failures')
        key = (row['method'], row['budget'])
        if row['id'] in seen_ids or row['sample_id'] in groups[key]:
            raise ValueError('Duplicate request or method/sample score; do not pool runs')
        seen_ids.add(row['id'])
        groups[key][row['sample_id']] = row
    return groups


def percentile(values, p):
    ordered = sorted(values)
    index = (len(ordered) - 1) * p
    lower = int(index)
    upper = min(lower + 1, len(ordered) - 1)
    return ordered[lower] + (index - lower) * (ordered[upper] - ordered[lower])


def rate(numerator, denominator):
    return 100 * numerator / denominator if denominator else None


def analyze(rows, candidate='closure', baseline='bm25', budget=1024,
            reference='full', reference_budget=0, resamples=10000, seed=2026):
    if resamples < 100:
        raise ValueError('Use at least 100 resamples; 10000 is recommended for final analysis')
    if candidate == baseline:
        raise ValueError('Candidate and baseline must differ')
    groups = load_groups(rows)
    keys = [(candidate, budget), (baseline, budget), (reference, reference_budget)]
    if any(key not in groups for key in keys):
        raise ValueError(f'Required groups not found: {keys}')
    c, b, f = [groups[key] for key in keys]
    ids = sorted(c)
    if set(ids) != set(b) or set(ids) != set(f):
        raise ValueError('Unpaired samples: preserve all planned requests, including failures')
    clusters = defaultdict(list)
    for sid in ids:
        if len({g[sid]['cluster_id'] for g in (c, b, f)}) != 1:
            raise ValueError('Cluster IDs disagree across methods')
        clusters[c[sid]['cluster_id']].append(sid)
    labels = sorted(clusters)
    # Aggregate whole clusters; a sampled cluster keeps all its questions and variants.
    totals = []
    for label in labels:
        members = clusters[label]
        totals.append((len(members), [sum(c[s][m] - b[s][m] for s in members) for m in METRICS]))
    boot = {m: [] for m in METRICS}
    if len(labels) >= 2:
        rng = random.Random(seed)
        for _ in range(resamples):
            sampled = [totals[rng.randrange(len(totals))] for _ in totals]
            n = sum(t[0] for t in sampled)
            for index, metric in enumerate(METRICS):
                boot[metric].append(100 * sum(t[1][index] for t in sampled) / n)
    warnings = []
    if len(labels) < 2:
        warnings.append('Fewer than two independent clusters: confidence intervals omitted.')
    elif len(labels) < 20:
        warnings.append('Fewer than 20 clusters: bootstrap intervals may be unstable; this is a diagnostic warning, not a universal adequacy threshold.')
    metrics = {}
    for metric in METRICS:
        difference = 100 * sum(c[s][metric] - b[s][metric] for s in ids) / len(ids)
        metrics[metric] = {
            'candidate_pct': rate(sum(c[s][metric] for s in ids), len(ids)),
            'baseline_pct': rate(sum(b[s][metric] for s in ids), len(ids)),
            'difference_pp': difference,
            'cluster_bootstrap_95ci_pp': [percentile(boot[metric], .025), percentile(boot[metric], .975)] if boot[metric] else None,
        }
    transitions = {'full_correct_candidate_correct': 0, 'full_correct_candidate_wrong': 0,
                   'full_wrong_candidate_correct': 0, 'full_wrong_candidate_wrong': 0}
    for sid in ids:
        left = 'correct' if f[sid]['answer_em'] else 'wrong'
        right = 'correct' if c[sid]['answer_em'] else 'wrong'
        transitions[f'full_{left}_candidate_{right}'] += 1
    correct_full = sum(f[s]['answer_em'] for s in ids)
    return {
        'status': 'ANALYSIS_OF_SUPPLIED_SCORES_NOT_PROOF_OF_REAL_INFERENCE',
        'candidate': candidate, 'baseline': baseline, 'budget': budget,
        'reference': reference, 'reference_budget': reference_budget,
        'n_questions': len(ids), 'n_clusters': len(labels),
        'interval_method': 'paired question-weighted percentile cluster bootstrap',
        'resamples': resamples, 'seed': seed, 'metrics': metrics,
        'missing_pct': {name: rate(sum(g[s]['missing'] for s in ids), len(ids))
                        for name, g in (('candidate', c), ('baseline', b), ('reference', f))},
        'transitions_vs_reference': transitions,
        'damage_pct': rate(transitions['full_correct_candidate_wrong'], correct_full),
        'rescue_pct': rate(transitions['full_wrong_candidate_correct'], len(ids) - correct_full),
        'warnings': warnings,
        'limits': ['No model-seed variability is estimated.',
                   'Joint exact evidence is a strict proxy, not semantic support.',
                   'No multiplicity correction, cost analysis or provenance authentication is performed.',
                   'Use official benchmark metrics separately where required.'],
    }


def markdown(result):
    lines = ['# Paired score analysis', '',
             '> Derived from supplied score records. This report does not verify that records came from real model inference.', '',
             f"Questions: {result['n_questions']} · Clusters: {result['n_clusters']} · Budget: {result['budget']} (unit must be read from the run manifest).", '',
             f"Candidate: `{result['candidate']}` · Baseline: `{result['baseline']}`", '',
             '| Metric | Candidate (%) | Baseline (%) | Difference (pp) | 95% cluster CI (pp) |',
             '|---|---:|---:|---:|---|']
    for metric, values in result['metrics'].items():
        ci = values['cluster_bootstrap_95ci_pp']
        interval = f'[{ci[0]:.2f}, {ci[1]:.2f}]' if ci else 'undefined'
        lines.append(f"| {metric} | {values['candidate_pct']:.2f} | {values['baseline_pct']:.2f} | {values['difference_pp']:.2f} | {interval} |")
    lines += ['', '## Full-context transitions', '', '| Transition | Count |', '|---|---:|']
    lines += [f'| {k} | {v} |' for k, v in result['transitions_vs_reference'].items()]
    for key in ('damage_pct', 'rescue_pct'):
        value = result[key]
        lines += ['', f"{key}: {value:.2f}%" if value is not None else f'{key}: undefined (zero denominator).']
    lines += ['', '## Missing predictions', '', '| Group | Missing (%) |', '|---|---:|']
    lines += [f'| {k} | {v:.2f} |' for k, v in result['missing_pct'].items()]
    lines += ['', '## Interpretation limits', ''] + ['- ' + x for x in result['warnings'] + result['limits']]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scores', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--budget', type=int, required=True)
    parser.add_argument('--candidate', default='closure')
    parser.add_argument('--baseline', default='bm25')
    parser.add_argument('--resamples', type=int, default=10000)
    parser.add_argument('--seed', type=int, default=2026)
    args = parser.parse_args()
    source = Path(args.scores)
    rows = [json.loads(line) for line in source.read_text(encoding='utf-8').splitlines() if line.strip()]
    result = analyze(rows, candidate=args.candidate, baseline=args.baseline,
                     budget=args.budget, resamples=args.resamples, seed=args.seed)
    result['scores_sha256'] = hashlib.sha256(source.read_bytes()).hexdigest()
    result['analysis_code_sha256'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if any((out / name).exists() for name in ('paired_analysis.json', 'paired_analysis.md')):
        raise FileExistsError('Analysis output exists; select a new output directory')
    for name, content in [('paired_analysis.json', json.dumps(result, ensure_ascii=False, indent=2)),
                          ('paired_analysis.md', markdown(result))]:
        # Avoid silently overwriting a previous report or even the score input.
        with (out / name).open('x', encoding='utf-8') as handle:
            handle.write(content)
    print(f'Wrote paired analysis for {len(rows)} supplied score records to {out}')


if __name__ == '__main__':
    main()
